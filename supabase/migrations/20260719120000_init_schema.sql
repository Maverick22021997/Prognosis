create table public.events (
  id bigint generated by default as identity primary key,

  season_id bigint not null
    references public.seasons(id)
    on update cascade
    on delete restrict,

  category_id bigint not null
    references public.event_categories(id)
    on update cascade
    on delete restrict,

  title text not null,
  slug text not null,
  description text,

  source_name text,
  source_url text,
  resolution_rule text not null,

  publish_at timestamptz not null,
  prediction_close_at timestamptz not null,
  expected_resolution_at timestamptz,

  resolved_at timestamptz,

  status public.event_status not null default 'draft',
  result public.prediction_side,

  cancel_reason text,
  is_featured boolean not null default false,

  predictions_count integer not null default 0,
  volume_gp bigint not null default 0,

  created_by uuid
    references public.profiles(id)
    on update cascade
    on delete set null,

  resolved_by uuid
    references public.profiles(id)
    on update cascade
    on delete set null,

  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),

  constraint events_title_length
    check (
      char_length(btrim(title)) between 5 and 250
    ),

  constraint events_slug_format
    check (
      slug ~ '^[a-z0-9]+(?:-[a-z0-9]+)*$'
    ),

  constraint events_resolution_rule_length
    check (
      char_length(btrim(resolution_rule)) between 10 and 2000
    ),

  constraint events_prediction_close_after_publish
    check (
      prediction_close_at > publish_at
    ),

  constraint events_resolution_after_close
    check (
      expected_resolution_at is null
      or expected_resolution_at >= prediction_close_at
    ),

  constraint events_resolved_at_valid
    check (
      resolved_at is null
      or resolved_at >= prediction_close_at
    ),

  constraint events_predictions_count_nonnegative
    check (
      predictions_count >= 0
    ),

  constraint events_volume_gp_nonnegative
    check (
      volume_gp >= 0
    ),

  constraint events_result_required_when_resolved
    check (
      status <> 'resolved'
      or result is not null
    ),

  constraint events_result_empty_when_not_resolved
    check (
      status = 'resolved'
      or result is null
    ),

  constraint events_cancel_reason_required
    check (
      status not in ('cancelled', 'void')
      or char_length(btrim(coalesce(cancel_reason, ''))) >= 5
    )
);


