create table public.predictions (
  id bigint generated by default as identity primary key,

  user_id uuid not null
    references public.profiles(id)
    on update cascade
    on delete restrict,

  season_id bigint not null
    references public.seasons(id)
    on update cascade
    on delete restrict,

  event_id bigint not null
    references public.events(id)
    on update cascade
    on delete restrict,

  prediction_side public.prediction_side not null,

  stake_amount bigint not null,
  odds_at_purchase numeric(10, 4) not null,

  potential_payout bigint not null,
  actual_payout bigint,

  status public.prediction_status not null default 'active',

  placed_at timestamptz not null default now(),
  resolved_at timestamptz,

  created_at timestamptz not null default now(),

  constraint predictions_user_event_unique
    unique (user_id, event_id),

  constraint predictions_stake_positive
    check (
      stake_amount > 0
    ),

  constraint predictions_odds_valid
    check (
      odds_at_purchase >= 1
      and odds_at_purchase <= 10
    ),

  constraint predictions_potential_payout_valid
    check (
      potential_payout >= stake_amount
    ),

  constraint predictions_actual_payout_nonnegative
    check (
      actual_payout is null
      or actual_payout >= 0
    ),

  constraint predictions_resolution_fields_valid
    check (
      (
        status = 'active'
        and resolved_at is null
        and actual_payout is null
      )
      or
      (
        status <> 'active'
        and resolved_at is not null
        and actual_payout is not null
      )
    ),

  constraint predictions_won_payout_valid
    check (
      status <> 'won'
      or actual_payout > 0
    ),

  constraint predictions_lost_payout_valid
    check (
      status <> 'lost'
      or actual_payout = 0
    ),

  constraint predictions_refund_payout_valid
    check (
      status not in ('refunded', 'void')
      or actual_payout = stake_amount
    )
);


create index predictions_user_placed_idx
  on public.predictions (
    user_id,
    placed_at desc
  );


